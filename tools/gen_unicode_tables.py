#!/usr/bin/env python3
"""Writes src/base/unicode_tables.inc, the Unicode data src/base/unicode.cpp needs, from Python's unicodedata.

    python3 tools/gen_unicode_tables.py src/base/unicode_tables.inc

The tables:
- case maps: each character's full lower and upper case (str.lower / str.upper of the one character, as SQL's
  lower() and upper() do) and its simple case fold (one character to one, what a case-insensitive match
  compares);
- character classes, as code point ranges: alphabetic, decimal digit, white space, word
  (\\w: letters, marks, decimal digits, connector punctuation and the joiners), cased and case-ignorable (for
  the final sigma);
- canonical normalization: each character's full canonical decomposition, its combining class, and the pairs
  that compose (Hangul is algorithmic, in the code);
- the Semitic vowel and cantillation marks a search may remove: the nonspacing marks of the Hebrew, Arabic,
  Syriac and Thaana blocks, and the Arabic tatweel.
"""
import sys
import unicodedata

MAX = 0x110000


def ranges(pred):
    out, start = [], None
    for cp in range(MAX + 1):
        ok = cp < MAX and not (0xD800 <= cp <= 0xDFFF) and pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def cat(cp):
    return unicodedata.category(chr(cp))


def c_string(s):
    return '"' + "".join(f"\\x{b:02x}" for b in s.encode("utf-8")) + '"'


SEMITIC_BLOCKS = [(0x0590, 0x05FF), (0x0600, 0x06FF), (0x0700, 0x074F), (0x0750, 0x077F), (0x0780, 0x07BF),
                  (0x0860, 0x086F), (0x0870, 0x089F), (0x08A0, 0x08FF), (0xFB1D, 0xFB4F)]


def main(path):
    out = [f"// Generated by tools/gen_unicode_tables.py (Unicode {unicodedata.unidata_version}): do not edit.",
           "// clang-format off"]

    def emit_ranges(name, pred):
        rs = ranges(pred)
        out.append(f"static const std::uint32_t {name}[][2] = {{")
        out.extend(f"    {{0x{a:X}, 0x{b:X}}}," for a, b in rs)
        out.append("};")

    emit_ranges("kAlpha", lambda cp: cat(cp)[0] == "L" or cat(cp) == "Nl")
    emit_ranges("kDigit", lambda cp: cat(cp) == "Nd")
    emit_ranges("kSpace", lambda cp: chr(cp).isspace())
    emit_ranges("kWord", lambda cp: cat(cp)[0] in "LM" or cat(cp) in ("Nd", "Pc") or cp in (0x200C, 0x200D))
    # Cased: Lowercase, Uppercase (which carry Other_Lowercase / Other_Uppercase, as str.islower and
    # str.isupper of one character read them) and Lt.
    emit_ranges("kCased", lambda cp: cat(cp) == "Lt" or chr(cp).islower() or chr(cp).isupper())
    # Case_Ignorable: Mn, Me, Cf, Lm, Sk, and Word_Break MidLetter, MidNumLet and Single_Quote.
    word_break_mid = {0x27, 0x2E, 0x3A, 0xB7, 0x387, 0x55F, 0x5F4, 0x2018, 0x2019, 0x2024, 0x2027, 0xFE13, 0xFE52,
                      0xFE55, 0xFF07, 0xFF0E, 0xFF1A}
    emit_ranges("kCaseIgnorable", lambda cp: cat(cp) in ("Mn", "Me", "Cf", "Lm", "Sk") or cp in word_break_mid)
    emit_ranges("kSemiticMark", lambda cp: cp == 0x0640 or (cat(cp) == "Mn" and any(a <= cp <= b for a, b in SEMITIC_BLOCKS)))

    out.append("struct CaseMapping { std::uint32_t cp; const char* to; };")
    for name, fn in (("kToLower", str.lower), ("kToUpper", str.upper)):
        out.append(f"static const CaseMapping {name}[] = {{")
        for cp in range(MAX):
            if 0xD800 <= cp <= 0xDFFF:
                continue
            m = fn(chr(cp))
            if m != chr(cp):
                out.append(f"    {{0x{cp:X}, {c_string(m)}}},")
        out.append("};")

    # Simple case fold: the one-character lower case of the one-character upper case (so σ, ς and Σ fold
    # together), else the one-character lower case.
    out.append("static const std::uint32_t kSimpleFold[][2] = {")
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        up = c.upper()
        f = up.lower() if len(up) == 1 and len(up.lower()) == 1 else (c.lower() if len(c.lower()) == 1 else c)
        if f != c:
            out.append(f"    {{0x{cp:X}, 0x{ord(f):X}}},")
    out.append("};")

    out.append("struct CombiningClass { std::uint32_t first; std::uint32_t last; std::uint8_t ccc; };")
    out.append("static const CombiningClass kCombiningClass[] = {")
    start, prev = None, None
    for cp in range(MAX + 1):
        v = unicodedata.combining(chr(cp)) if cp < MAX and not (0xD800 <= cp <= 0xDFFF) else 0
        if start is not None and (v != prev or cp == MAX):
            out.append(f"    {{0x{start:X}, 0x{cp - 1:X}, {prev}}},")
            start = None
        if v != 0 and start is None:
            start, prev = cp, v
    out.append("};")

    out.append("static const CaseMapping kDecompose[] = {")
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
            continue
        d = unicodedata.normalize("NFD", chr(cp))
        if d != chr(cp):
            out.append(f"    {{0x{cp:X}, {c_string(d)}}},")
    out.append("};")

    pairs = []
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF or 0xAC00 <= cp <= 0xD7A3:
            continue
        raw = unicodedata.decomposition(chr(cp))
        if not raw or raw.startswith("<"):
            continue
        parts = [int(p, 16) for p in raw.split()]
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(cp)) == chr(cp):
            pairs.append((parts[0], parts[1], cp))
    pairs.sort()
    out.append("struct Composition { std::uint32_t first; std::uint32_t second; std::uint32_t composed; };")
    out.append("static const Composition kCompose[] = {")
    out.extend(f"    {{0x{a:X}, 0x{b:X}, 0x{c:X}}}," for a, b, c in pairs)
    out.append("};")
    out.append("// clang-format on")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
