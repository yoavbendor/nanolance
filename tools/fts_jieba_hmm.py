"""Generate src/fts_jieba_hmm_data.inc: jieba-rs 0.10's built-in HMM model, zstd-compressed.

usage: fts_jieba_hmm.py <jieba-macros-0.10.0/src/hmm.model> <out.inc>

The model text is read the way jieba-macros' generate_hmm_data! reads it. The binary layout the C++ side
parses (little-endian): u32 version (1); 4 f64 initial probabilities (B, E, M, S); 16 f64 transition
probabilities, row-major from state; then for each of the 4 emission tables: u32 count, then count pairs
of (u32 code point, f64 probability). Every float is Python's float() of the model's decimal text, which
is correctly rounded, as Rust's f64 parse is. Needs the `zstandard` package (python3 -m pip install zstandard).
"""

import struct
import sys

import zstandard


def parse(path):
    with open(path, encoding="utf-8") as f:
        lines = [line.rstrip("\n") for line in f]
    data = [line for line in lines if line and not line.startswith("#")]
    initial = [float(v) for v in data[0].split()]
    assert len(initial) == 4, initial
    trans_start = lines.index("#prob_trans 4x4 matrix") + 1
    trans_rows = [line for line in lines[trans_start:] if line and not line.startswith("#")][:4]
    trans = [float(v) for row in trans_rows for v in row.split()]
    assert len(trans) == 16, trans
    emit_start = lines.index("#prob_emit 4 lines") + 1
    emit_lines = [line for line in lines[emit_start:] if line and not line.startswith("#")][:4]
    assert len(emit_lines) == 4
    tables = []
    for line in emit_lines:
        table = []
        for pair in line.split(","):
            key, prob = pair.split(":")
            assert len(key) == 1, key
            table.append((ord(key), float(prob)))
        tables.append(table)
    return initial, trans, tables


def main():
    initial, trans, tables = parse(sys.argv[1])
    raw = struct.pack("<I", 1) + struct.pack("<4d", *initial) + struct.pack("<16d", *trans)
    for table in tables:
        raw += struct.pack("<I", len(table))
        for cp, prob in sorted(table):
            raw += struct.pack("<Id", cp, prob)
    packed = zstandard.ZstdCompressor(level=19).compress(raw)
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Copyright (c) 2026 Yoav Bendor",
        "// Generated by tools/fts_jieba_hmm.py from jieba-rs 0.10.0's hmm.model (MIT). Do not edit.",
        f"// raw {len(raw)} bytes, zstd {len(packed)} bytes.",
        f"static const std::size_t kJiebaHmmRawSize = {len(raw)};",
        f"static const std::size_t kJiebaHmmZstdSize = {len(packed)};",
        "static const std::uint8_t kJiebaHmmZstd[] = {",
    ]
    for i in range(0, len(packed), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in packed[i:i + 16]) + ",")
    out.append("};")
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"raw {len(raw)} bytes, zstd {len(packed)} bytes")


if __name__ == "__main__":
    main()
