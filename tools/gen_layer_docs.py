"""Generated layer docs for nanolance: docs/LAYERS.md, and a layer-deps block in each src/<layer>/README.md.

The layers, and what each one is, come from tools/layout.py. Which layer uses which comes from the real
#include edges that tools/check_layers.py collects, so the table and the diagram match the code. A layer may
use any layer below it. Each block says which layers its layer uses directly and which layers use it directly.

Usage: gen_layer_docs.py [--root PATH] [--check]
  (no flag)  write docs/LAYERS.md and the layer-deps block of each src/<layer>/README.md
  --check    write nothing; exit 1 and name each file whose generated content differs from what is on disk
Exit codes: 0 ok (or up to date), 1 out of date or the layout has errors, 2 usage error.
"""
import argparse
import sys
from pathlib import Path

import check_layers

HERE = Path(__file__).resolve().parent
DOC = "docs/LAYERS.md"
START = "<!-- layer-deps:start -->"
END = "<!-- layer-deps:end -->"


def build(root):
    """Layer order (bottom first), direct uses and used-by per layer, and any layout errors."""
    layout, layer_of, errors, _, _, edges = check_layers.collect(root)
    names = [name for name, _, _ in layout.LAYERS]
    uses = {name: set() for name in names}
    used_by = {name: set() for name in names}
    for includer, included, _, _ in edges:
        a, b = layer_of[includer], layer_of[included]
        if a != b:
            uses[a].add(b)
            used_by[b].add(a)
    return layout, names, uses, used_by, errors


def listed(order, found, link=None):
    """Layer names of `found`, in layer order, comma-separated; 'none' when empty."""
    items = [n for n in order if n in found]
    if not items:
        return "none"
    if link is None:
        return ", ".join(items)
    return ", ".join(link(n) for n in items)


def layers_md(layout, names, uses, used_by):
    dirs = {name: d for name, d, _ in layout.LAYERS}
    what = {name: w for name, _, w in layout.LAYERS}
    number = {name: i + 1 for i, name in enumerate(names)}
    top_first = list(reversed(names))
    out = [
        "<!-- Generated by tools/gen_layer_docs.py. Do not edit by hand. -->",
        "# Layers",
        "",
        "*Generated by `tools/gen_layer_docs.py` from `tools/layout.py` and the includes in `src/`. "
        "Do not edit by hand.*",
        "",
        "A layer may use any layer below it. The table lists the layers top first, and the diagram shows the "
        "layers each one actually uses.",
        "",
        "| Number | Layer | What it is | Uses | Used by |",
        "|---|---|---|---|---|",
    ]
    for name in top_first:
        description = what[name].replace("|", "\\|")
        out.append(
            f"| {number[name]} | [{name}](../src/{dirs[name]}/README.md) | {description} "
            f"| {listed(names, uses[name])} | {listed(names, used_by[name])} |")
    out += ["", "```mermaid", "graph TD"]
    for name in top_first:
        out.append(f'  {name}["{number[name]} {name}"]')
    for name in top_first:
        for dep in sorted(uses[name], key=names.index, reverse=True):
            out.append(f"  {name} --> {dep}")
    out += ["```", ""]
    return "\n".join(out)


def block_lines(name, layout, names, uses, used_by):
    dirs = {n: d for n, d, _ in layout.LAYERS}
    link = lambda n: f"[{n}](../{dirs[n]}/README.md)"
    total = len(names)
    return [
        f"Layer {names.index(name) + 1} of {total} (1 is the bottom, {total} the top). "
        f"Uses: {listed(names, uses[name], link)}. Used by: {listed(names, used_by[name], link)}. "
        "See [docs/LAYERS.md](../../docs/LAYERS.md).",
    ]


def with_block(text, block):
    """README text with the layer-deps block inserted after the first heading, or its content replaced."""
    lines = text.split("\n")
    marked = [START, *block, END]
    if START in lines:
        s = lines.index(START)
        e = lines.index(END)
        return "\n".join(lines[:s] + marked + lines[e + 1:])
    h = next(i for i, line in enumerate(lines) if line.startswith("# "))
    rest = lines[h + 1:]
    while rest and rest[0].strip() == "":
        rest.pop(0)
    return "\n".join(lines[:h + 1] + [""] + marked + [""] + rest)


def outputs(root):
    """Map of repo-relative path -> generated content, and any layout errors."""
    layout, names, uses, used_by, errors = build(root)
    dirs = {n: d for n, d, _ in layout.LAYERS}
    files = {DOC: layers_md(layout, names, uses, used_by)}
    for name in names:
        path = f"src/{dirs[name]}/README.md"
        text = (root / path).read_text(encoding="utf-8")
        files[path] = with_block(text, block_lines(name, layout, names, uses, used_by))
    return files, errors


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate docs/LAYERS.md and the layer-deps block of each layer README.")
    ap.add_argument("--root", type=Path, default=HERE.parent,
                    help="tree to generate for (default: the repository this script is in)")
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 and name each file that is out of date")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    if not root.is_dir():
        ap.error(f"--root {args.root} is not a directory")

    files, errors = outputs(root)
    if errors:
        print("the layout has errors (tools/check_layers.py lists them); nothing generated:", file=sys.stderr)
        for e in errors:
            print(f"  {e}", file=sys.stderr)
        return 1

    stale = []
    for rel, text in files.items():
        path = root / rel
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            stale.append(rel)

    if args.check:
        for rel in stale:
            print(f"out of date: {rel} (run: python3 tools/gen_layer_docs.py)")
        if stale:
            return 1
        print(f"layer docs are up to date ({len(files)} files)")
        return 0

    for rel in stale:
        (root / rel).write_text(files[rel], encoding="utf-8")
        print(f"wrote {rel}")
    if not stale:
        print("layer docs unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
